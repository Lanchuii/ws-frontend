import { FormEvent, useMemo, useState } from 'react';
import { FaCheck, FaTimes } from 'react-icons/fa';
import {
  AutoGeneratedScheduleRow,
  AutoGenerationPreview,
  confirmAutoGeneration,
  previewAutoGeneration,
} from '../../services/schedules';
import { Worker, WorkerRole } from '../../models/Worker';
import {
  getServiceTypeOption,
  ServiceTypeValue,
  serviceTypes,
} from '../../constants/serviceTypes';

interface Props {
  monthDate: Date;
  workers: Worker[];
  onClose: () => void;
  onConfirmed: () => void;
}

interface GenerationColumn {
  label: string;
  roles: WorkerRole[];
}

const mainColumns: GenerationColumn[] = [
  { label: 'Leader', roles: ['Leader'] },
  { label: 'Backup', roles: ['Backup'] },
  { label: 'Acoustic', roles: ['Acoustic'] },
  { label: 'Electric', roles: ['Electric'] },
  { label: 'Bass', roles: ['Bass'] },
  { label: 'Keyboard', roles: ['Keyboard'] },
  { label: 'Drums', roles: ['Drums'] },
];

const nonMainColumns: GenerationColumn[] = [
  { label: 'Leader', roles: ['Leader'] },
  { label: 'Acoustic', roles: ['Acoustic'] },
  { label: 'Bass', roles: ['Bass'] },
  { label: 'Drums / Beatbox', roles: ['Drums', 'Beatbox'] },
];

const midweekColumns: GenerationColumn[] = [
  { label: 'Leader', roles: ['Leader'] },
  { label: 'Acoustic / Keyboard', roles: ['Acoustic', 'Keyboard'] },
  { label: 'Bass', roles: ['Bass'] },
  { label: 'Drums / Beatbox', roles: ['Drums', 'Beatbox'] },
];

const allWorkerRoles: WorkerRole[] = [
  'Leader',
  'Backup',
  'Acoustic',
  'Electric',
  'Bass',
  'Keyboard',
  'Drums',
  'Beatbox',
];

const AutoGenerateScheduleModal = ({ monthDate, workers, onClose, onConfirmed }: Props) => {
  const [includeOptionalRoles, setIncludeOptionalRoles] = useState(true);
  const [allowYouthBackupFallback, setAllowYouthBackupFallback] = useState(true);
  const [serviceType, setServiceType] = useState<ServiceTypeValue>('main');
  const [preview, setPreview] = useState<AutoGenerationPreview>();
  const [editableRows, setEditableRows] = useState<AutoGeneratedScheduleRow[]>([]);
  const [selectedDates, setSelectedDates] = useState<Set<string>>(new Set());
  const [error, setError] = useState('');
  const [loadingPreview, setLoadingPreview] = useState(false);
  const [confirming, setConfirming] = useState(false);

  const year = monthDate.getFullYear();
  const month = monthDate.getMonth() + 1;
  const monthLabel = useMemo(() => {
    return new Intl.DateTimeFormat('en-US', {
      month: 'long',
      year: 'numeric',
    }).format(monthDate);
  }, [monthDate]);
  const serviceTypeOption = getServiceTypeOption(serviceType);
  const columns = serviceType === 'main'
    ? mainColumns
    : serviceType === 'midweek'
      ? midweekColumns
      : nonMainColumns;
  const weekdayLabel = getGenerationWeekdayLabel(serviceType);

  const workersByRole = useMemo(() => {
    return allWorkerRoles.reduce<Record<string, Worker[]>>((acc, role) => {
      acc[role] = workers
        .filter((worker) => {
          return worker.status === 'active' && worker.roles.includes(role);
        })
        .sort((a, b) => a.name.localeCompare(b.name));
      return acc;
    }, {});
  }, [workers]);
  const selectableRows = editableRows.filter(isRowSaveable);
  const selectedRows = selectableRows.filter((row) => selectedDates.has(row.date));

  const handlePreview = async (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    setError('');
    setLoadingPreview(true);

    try {
      const result = await previewAutoGeneration({
        year,
        month,
        service_type: serviceType,
        includeOptionalRoles,
        allowYouthBackupFallback,
      });
      setPreview(result);
      setEditableRows(result.rows);
      setSelectedDates(
        new Set(
          result.rows.filter(isRowSaveable).map((row) => row.date),
        ),
      );
    } catch {
      setError('Auto-generation preview could not be created.');
    } finally {
      setLoadingPreview(false);
    }
  };

  const handleConfirm = async () => {
    setError('');

    const invalidSelectedRow = selectedRows.find((row) => !isRowSaveable(row));

    if (invalidSelectedRow) {
      setError(`${invalidSelectedRow.date} still needs attention before saving.`);
      return;
    }

    setConfirming(true);

    try {
      await confirmAutoGeneration({
        schedules: selectedRows.map((row) => ({
          date: row.date,
          service_type: row.service_type,
          assignments: row.assignments.map((assignment) => ({
            role: assignment.role,
            worker_id: assignment.worker_id,
          })),
        })),
      });
      await onConfirmed();
      onClose();
    } catch {
      setError('Generated schedules could not be saved. Review conflicts and try again.');
    } finally {
      setConfirming(false);
    }
  };

  const toggleRow = (row: AutoGeneratedScheduleRow) => {
    if (!isRowSaveable(row)) {
      return;
    }

    setSelectedDates((current) => {
      const next = new Set(current);

      if (next.has(row.date)) {
        next.delete(row.date);
      } else {
        next.add(row.date);
      }

      return next;
    });
  };

  const handleAssignmentChange = (
    row: AutoGeneratedScheduleRow,
    column: GenerationColumn,
    selection: string,
  ) => {
    const [role, workerId] = selection.split(':') as [WorkerRole, string];
    const worker = workers.find((item) => item._id === workerId);

    setEditableRows((currentRows) => {
      return currentRows.map((currentRow) => {
        if (currentRow.date !== row.date) {
          return currentRow;
        }

        const otherAssignments = currentRow.assignments.filter((assignment) => {
          return !column.roles.includes(assignment.role as WorkerRole);
        });

        if (!worker) {
          return {
            ...currentRow,
            assignments: otherAssignments,
          };
        }

        return {
          ...currentRow,
          assignments: [
            ...otherAssignments,
            {
              role,
              worker_id: worker._id,
              worker_name: worker.name,
            },
          ].sort((a, b) => {
            return getColumnIndex(a.role, columns) - getColumnIndex(b.role, columns);
          }),
        };
      });
    });
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-950/50 px-4 py-6">
      <section className="max-h-full w-full max-w-[1500px] overflow-auto rounded-lg bg-white shadow-xl">
        <div className="flex items-start justify-between gap-4 border-b border-slate-200 p-5">
          <div>
            <p className="text-sm font-semibold uppercase tracking-wide text-amber-700">
              Auto generate
            </p>
            <h2 className="mt-1 text-xl font-bold text-slate-950">
              {serviceTypeOption.label} schedules for {monthLabel}
            </h2>
            <p className="mt-1 text-sm text-slate-600">
              Preview every {weekdayLabel} first, then save the generated schedules you approve.
            </p>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="inline-flex h-9 w-9 items-center justify-center rounded-md text-slate-500 hover:bg-slate-100 hover:text-slate-950"
            aria-label="Close auto-generation"
          >
            <FaTimes />
          </button>
        </div>

        <div className="space-y-5 p-5">
          {error && (
            <div className="rounded-md border border-red-200 bg-red-50 px-3 py-2 text-sm font-medium text-red-700">
              {error}
            </div>
          )}

          <form
            onSubmit={handlePreview}
            className={`grid items-end gap-5 rounded-md border border-slate-200 bg-slate-50 p-4 sm:grid-cols-2 xl:gap-6 ${
              serviceType === 'main'
                ? 'xl:grid-cols-[160px_minmax(240px,320px)_minmax(190px,1fr)_minmax(190px,1fr)_145px]'
                : 'xl:grid-cols-[160px_minmax(240px,360px)_1fr_145px]'
            }`}
          >
              <div>
                <p className="text-xs font-bold uppercase text-slate-500">Month</p>
                <p className="mt-1 flex h-10 items-center text-sm font-bold text-slate-950">
                  {monthLabel}
                </p>
              </div>
              <label className="block min-w-0">
                <span className="text-xs font-bold uppercase text-slate-500">Service type</span>
                <select
                  value={serviceType}
                  onChange={(event) => {
                    setServiceType(event.target.value as ServiceTypeValue);
                    setPreview(undefined);
                    setEditableRows([]);
                    setSelectedDates(new Set());
                  }}
                  className="mt-1 h-10 w-full rounded-md border border-slate-300 bg-white px-3 text-sm font-semibold text-slate-950 outline-none focus:border-amber-500 focus:ring-2 focus:ring-amber-100"
                >
                  {serviceTypes.map((option) => (
                    <option key={option.value} value={option.value}>
                      {option.label}
                    </option>
                  ))}
                </select>
              </label>
              <label className="flex h-10 items-center gap-2 whitespace-nowrap text-sm font-semibold text-slate-700">
                <input
                  type="checkbox"
                  checked={includeOptionalRoles}
                  onChange={(event) => setIncludeOptionalRoles(event.target.checked)}
                  className="h-4 w-4 rounded border-slate-300 text-amber-600 focus:ring-amber-500"
                />
                Include optional roles
              </label>
              {serviceType === 'main' && (
              <label className="flex h-10 items-center gap-2 whitespace-nowrap text-sm font-semibold text-slate-700">
                <input
                  type="checkbox"
                  checked={allowYouthBackupFallback}
                  onChange={(event) => setAllowYouthBackupFallback(event.target.checked)}
                  className="h-4 w-4 rounded border-slate-300 text-amber-600 focus:ring-amber-500"
                />
                Youth backup fallback
              </label>
              )}

            <button
              type="submit"
              disabled={loadingPreview}
              className={`col-span-2 inline-flex h-10 items-center justify-center rounded-md bg-slate-950 px-4 text-sm font-semibold text-white hover:bg-slate-800 disabled:cursor-not-allowed disabled:opacity-60 xl:col-span-1 ${
                serviceType === 'main' ? '' : 'xl:col-start-4'
              }`}
            >
              {loadingPreview ? 'Generating...' : 'Generate preview'}
            </button>
          </form>

          {preview && (
            <div className="overflow-hidden rounded-md border border-slate-200">
              <div className="flex flex-col gap-2 border-b border-slate-200 px-4 py-3 sm:flex-row sm:items-center sm:justify-between">
                <div>
                  <p className="text-sm font-bold text-slate-950">Preview</p>
                  <p className="text-xs font-semibold text-slate-500">
                    {selectedRows.length} generated schedule
                    {selectedRows.length === 1 ? '' : 's'} selected
                  </p>
                </div>
                <button
                  type="button"
                  onClick={handleConfirm}
                  disabled={!selectedRows.length || confirming}
                  className="inline-flex items-center justify-center gap-2 rounded-md bg-amber-600 px-4 py-2 text-sm font-semibold text-white hover:bg-amber-700 disabled:cursor-not-allowed disabled:opacity-60"
                >
                  <FaCheck />
                  {confirming ? 'Saving...' : 'Save selected'}
                </button>
              </div>

              <div className="overflow-x-auto">
                <table
                  className={
                    serviceType === 'main'
                      ? 'min-w-[1520px] table-fixed border-collapse text-sm'
                      : 'min-w-[880px] table-fixed border-collapse text-sm'
                  }
                >
                  <thead className="border-b border-slate-200 bg-amber-50 text-xs font-bold uppercase text-slate-600">
                    <tr>
                      <th className="w-14 px-3 py-3 text-left">Save</th>
                      <th className="w-28 px-3 py-3 text-left">Date</th>
                      <th className="w-56 px-3 py-3 text-left">Status</th>
                      {columns.map((column) => (
                        <th key={column.label} className="w-40 px-3 py-3 text-left">
                          {column.label}
                        </th>
                      ))}
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-200">
                    {editableRows.map((row) => {
                      const rowWarnings = getRowWarnings(row);
                      const rowStatus = getDisplayStatus(row);

                      return (
                      <tr key={row.date} className="align-top">
                        <td className="px-3 py-3">
                          <input
                            type="checkbox"
                            checked={selectedDates.has(row.date)}
                            disabled={!isRowSaveable(row)}
                            onChange={() => toggleRow(row)}
                            className="h-4 w-4 rounded border-slate-300 text-amber-600 focus:ring-amber-500 disabled:opacity-40"
                            aria-label={`Save generated schedule for ${row.date}`}
                          />
                        </td>
                        <td className="px-3 py-3 font-bold text-slate-950">
                          {formatPreviewDate(row.date)}
                        </td>
                        <td className="px-3 py-3">
                          <span
                            className={`inline-flex whitespace-nowrap rounded-full px-3 py-1 text-xs font-bold uppercase ${getStatusClassName(rowStatus)}`}
                          >
                            {rowStatus.replace('_', ' ')}
                          </span>
                          {rowWarnings.length > 0 && (
                            <div className="mt-2 space-y-1">
                              {rowWarnings.map((warning) => (
                                <p
                                  key={warning}
                                  className="break-words text-xs font-semibold leading-4 text-red-700"
                                >
                                  {warning}
                                </p>
                              ))}
                            </div>
                          )}
                        </td>
                        {columns.map((column) => (
                          <td key={column.label} className="px-3 py-3">
                            {row.status === 'skipped' ? (
                              <span className="font-semibold text-slate-950">
                                {getWorkerForRoles(row, column.roles) || '-'}
                              </span>
                            ) : (
                              <select
                                value={getWorkerSelection(row, column.roles)}
                                onChange={(event) =>
                                  handleAssignmentChange(row, column, event.target.value)
                                }
                                className="w-full min-w-36 rounded-md border border-slate-300 px-2 py-1 text-sm font-semibold text-slate-950 outline-none focus:border-amber-500 focus:ring-2 focus:ring-amber-100"
                                aria-label={`${column.label} for ${row.date}`}
                              >
                                <option value="">-</option>
                                {getWorkerOptions(column, workersByRole).map(({ worker, role }) => (
                                  <option key={`${role}-${worker._id}`} value={`${role}:${worker._id}`}>
                                    {worker.name}{column.roles.length > 1 ? ` (${role})` : ''}
                                  </option>
                                ))}
                              </select>
                            )}
                          </td>
                        ))}
                      </tr>
                    );
                    })}
                  </tbody>
                </table>
              </div>
            </div>
          )}
        </div>
      </section>
    </div>
  );
};

const getWorkerForRoles = (row: AutoGeneratedScheduleRow, roles: WorkerRole[]) => {
  return row.assignments.find((assignment) => {
    return roles.includes(assignment.role as WorkerRole);
  })?.worker_name;
};

const getWorkerSelection = (row: AutoGeneratedScheduleRow, roles: WorkerRole[]) => {
  const assignment = row.assignments.find((item) => {
    return roles.includes(item.role as WorkerRole);
  });

  return assignment ? `${assignment.role}:${assignment.worker_id}` : '';
};

const getColumnIndex = (role: string, columns: GenerationColumn[]) => {
  const index = columns.findIndex((column) => {
    return column.roles.includes(role as WorkerRole);
  });
  return index === -1 ? columns.length : index;
};

const getRowWarnings = (row: AutoGeneratedScheduleRow) => {
  if (row.status === 'skipped') {
    return row.warnings;
  }

  const requiredColumns = row.service_type === 'main'
    ? mainColumns.filter((column) => {
        return ['Leader', 'Acoustic', 'Bass', 'Drums'].includes(column.roles[0]);
      })
    : row.service_type === 'midweek'
      ? midweekColumns.slice(0, 2)
      : nonMainColumns.slice(0, 2);
  const warnings = requiredColumns
    .filter((column) => !getWorkerSelection(row, column.roles))
    .map((column) => `Missing required role: ${column.label}`);
  if (hasUnsupportedDuplicateWorker(row)) {
    warnings.push('A worker cannot be assigned to multiple roles.');
  }

  return warnings;
};

const getDisplayStatus = (row: AutoGeneratedScheduleRow) => {
  if (row.status === 'skipped') {
    return row.status;
  }

  return getRowWarnings(row).length ? 'needs_attention' : 'generated';
};

const isRowSaveable = (row: AutoGeneratedScheduleRow) => {
  return row.status !== 'skipped' && getRowWarnings(row).length === 0;
};

const formatPreviewDate = (dateValue: string) => {
  const [year, month, day] = dateValue.split('-').map(Number);

  return new Intl.DateTimeFormat('en-US', {
    month: 'short',
    day: 'numeric',
  }).format(new Date(year, month - 1, day));
};

const getWorkerOptions = (
  column: GenerationColumn,
  workersByRole: Record<string, Worker[]>,
) => {
  const seenWorkerIds = new Set<string>();

  return column.roles.flatMap((role) => {
    return (workersByRole[role] ?? [])
      .filter((worker) => {
        if (seenWorkerIds.has(worker._id)) {
          return false;
        }

        seenWorkerIds.add(worker._id);
        return true;
      })
      .map((worker) => ({ worker, role }));
  });
};

const getGenerationWeekdayLabel = (serviceType: ServiceTypeValue) => {
  if (serviceType === 'youth') {
    return 'Saturday';
  }

  if (serviceType === 'midweek') {
    return 'Wednesday';
  }

  return 'Sunday';
};

const hasUnsupportedDuplicateWorker = (row: AutoGeneratedScheduleRow) => {
  const rolesByWorker = row.assignments.reduce<Map<string, WorkerRole[]>>(
    (roles, assignment) => {
      const workerRoles = roles.get(assignment.worker_id) ?? [];
      workerRoles.push(assignment.role as WorkerRole);
      roles.set(assignment.worker_id, workerRoles);
      return roles;
    },
    new Map(),
  );

  return [...rolesByWorker.values()].some((roles) => {
    if (roles.length === 1) {
      return false;
    }

    const roleSet = new Set(roles);
    return !(
      roles.length === 2 &&
      roleSet.has('Acoustic') &&
      (roleSet.has('Leader') || roleSet.has('Backup'))
    );
  });
};

const getStatusClassName = (status: AutoGeneratedScheduleRow['status']) => {
  if (status === 'generated') {
    return 'bg-emerald-50 text-emerald-700 ring-1 ring-emerald-200';
  }

  if (status === 'skipped') {
    return 'bg-slate-100 text-slate-600 ring-1 ring-slate-200';
  }

  return 'bg-red-50 text-red-700 ring-1 ring-red-200';
};

export default AutoGenerateScheduleModal;
