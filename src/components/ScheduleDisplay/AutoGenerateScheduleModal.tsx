import { FormEvent, useMemo, useState } from 'react';
import { FaTimes } from 'react-icons/fa';
import {
  AutoGeneratedScheduleRow,
  AutoGenerationPreview,
  AssignmentConstraint,
  confirmAutoGeneration,
  fetchAssignmentConstraints,
  getScheduleRequestConflicts,
  previewAutoGeneration,
} from '../../services/schedules';
import { Worker } from '../../models/Worker';
import { ServiceTypeConfiguration, WorkerGroup } from '../../models/ServiceConfiguration';
import { getSlotEligibility, isWorkerEligible } from '../../utils/serviceRules';
import EditableScheduleTable from './EditableScheduleTable';
import {
  isScheduleRowSaveable,
  withConstraintConflicts,
} from './scheduleAssignmentTable';

interface Props {
  monthDate: Date;
  workers: Worker[];
  serviceTypes: ServiceTypeConfiguration[];
  workerGroups: WorkerGroup[];
  onClose: () => void;
  onConfirmed: () => Promise<void> | void;
}

type WorkerPools = Record<string, Record<string, string[]>>;

const AutoGenerateScheduleModal = ({ monthDate, workers, serviceTypes, workerGroups, onClose, onConfirmed }: Props) => {
  const [includeOptionalRoles, setIncludeOptionalRoles] = useState(true);
  const [allowYouthBackupFallback, setAllowYouthBackupFallback] = useState(true);
  const availableServiceTypes = serviceTypes.filter(
    (item) => item.is_active && item.auto_generation_enabled && item.recurrence.type === 'weekly',
  );
  const [selectedServiceTypes, setSelectedServiceTypes] = useState<Set<string>>(
    () => new Set(availableServiceTypes[0] ? [availableServiceTypes[0].code] : []),
  );
  const [workerPools, setWorkerPools] = useState<WorkerPools>({});
  const [preview, setPreview] = useState<AutoGenerationPreview>();
  const [editableRows, setEditableRows] = useState<AutoGeneratedScheduleRow[]>([]);
  const [selectedRowKeys, setSelectedRowKeys] = useState<Set<string>>(new Set());
  const [error, setError] = useState('');
  const [saveSummary, setSaveSummary] = useState('');
  const [constraintsByDate, setConstraintsByDate] = useState<Record<string, AssignmentConstraint[]>>({});
  const [loadingPreview, setLoadingPreview] = useState(false);
  const [confirming, setConfirming] = useState(false);

  const year = monthDate.getFullYear();
  const month = monthDate.getMonth() + 1;
  const monthLabel = useMemo(() => {
    return new Intl.DateTimeFormat('en-US', {
      month: 'long',
      year: 'numeric',
    }).format(monthDate);
  }, [monthDate]);
  const selectedServiceTypeConfigs = availableServiceTypes.filter((item) =>
    selectedServiceTypes.has(item.code),
  );

  const resetPreview = () => {
    setPreview(undefined);
    setEditableRows([]);
    setSelectedRowKeys(new Set());
    setConstraintsByDate({});
    setError('');
    setSaveSummary('');
  };

  const getConstraintsForService = (serviceTypeCode: string) => {
    const next = Object.fromEntries(
      Object.entries(constraintsByDate).map(([date, constraints]) => [date, [...constraints]]),
    ) as Record<string, AssignmentConstraint[]>;

    editableRows.forEach((row) => {
      if (
        row.service_type === serviceTypeCode ||
        !selectedRowKeys.has(getRowKey(row)) ||
        row.status === 'skipped' ||
        row.save_status === 'saved'
      ) {
        return;
      }

      const dateConstraints = next[row.date] ?? [];
      row.assignments.forEach((assignment) => {
        dateConstraints.push({
          worker_id: assignment.worker_id,
          worker_name: assignment.worker_name,
          code: 'WORKER_ALREADY_ASSIGNED',
          message: `${assignment.worker_name} is selected for another generated service on this date`,
          blocking_schedule: {
            id: `preview:${row.service_type}:${row.date}`,
            service_type: row.service_type,
            role: assignment.role,
            slot_key: assignment.slot_key,
          },
        });
      });
      next[row.date] = dateConstraints;
    });

    return next;
  };

  const selectedRows = editableRows.filter((row) => {
    if (!selectedRowKeys.has(getRowKey(row))) return false;
    const serviceType = availableServiceTypes.find((item) => item.code === row.service_type);
    if (!serviceType) return false;
    return isScheduleRowSaveable(
      withConstraintConflicts(
        row,
        getConstraintsForService(row.service_type)[row.date] ?? [],
      ),
      serviceType,
    );
  });

  const handlePreview = async (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    setError('');
    setSaveSummary('');

    if (!selectedServiceTypeConfigs.length) {
      setError('Select at least one service type.');
      return;
    }

    setLoadingPreview(true);

    try {
      const [result, constraints] = await Promise.all([
        previewAutoGeneration({
          year,
          month,
          service_types: selectedServiceTypeConfigs.map((item) => item.code),
          worker_pools: selectedServiceTypeConfigs.flatMap((serviceType) =>
            Object.entries(workerPools[serviceType.code] ?? {}).flatMap(([slotKey, workerIds]) =>
              workerIds.length
                ? [{
                    service_type: serviceType.code,
                    slot_key: slotKey,
                    worker_ids: workerIds,
                  }]
                : [],
            ),
          ),
          includeOptionalRoles,
          allowYouthBackupFallback,
        }),
        fetchAssignmentConstraints(year, month),
      ]);
      const nextConstraints = Object.fromEntries(
        constraints.dates.map((item) => [item.date, item.blocked_workers]),
      );
      setConstraintsByDate(nextConstraints);
      setPreview(result);
      setEditableRows(result.rows);
      setSelectedRowKeys(
        new Set(
          result.rows
            .filter((row) => {
              const serviceType = selectedServiceTypeConfigs.find(
                (item) => item.code === row.service_type,
              );
              return serviceType && isScheduleRowSaveable(
                withConstraintConflicts(row, nextConstraints[row.date] ?? []),
                serviceType,
              );
            })
            .map(getRowKey),
        ),
      );
    } catch {
      setError('Auto-generation preview could not be created.');
    } finally {
      setLoadingPreview(false);
    }
  };

  const handleConfirm = async () => {
    setError('');
    setSaveSummary('');

    if (!selectedRows.length) {
      setError('No selected schedules are ready to save. Resolve the highlighted conflicts first.');
      return;
    }

    setConfirming(true);

    try {
      const selectedKeys = new Set(selectedRows.map(getRowKey));
      const locallyBlockedKeys = [...selectedRowKeys].filter((key) => !selectedKeys.has(key));
      const result = await confirmAutoGeneration({
        schedules: selectedRows.map((row) => ({
          date: row.date,
          service_type: row.service_type,
          assignments: row.assignments.map((assignment) => ({
            slot_key: assignment.slot_key,
            role: assignment.role,
            worker_id: assignment.worker_id,
          })),
        })),
      });
      const resultsByKey = new Map(
        result.items.map((item) => [`${item.service_type}:${item.date}`, item]),
      );
      setEditableRows((current) => current.map((row) => {
        const item = resultsByKey.get(getRowKey(row));
        if (!item) return row;
        return item.status === 'created'
          ? { ...row, save_status: 'saved', conflicts: [] }
          : { ...row, conflicts: item.conflicts ?? [{
              code: 'INVALID_ASSIGNMENT',
              date: row.date,
              message: item.message ?? 'Schedule could not be saved',
            }] };
      }));
      setSelectedRowKeys(new Set(
        [
          ...locallyBlockedKeys,
          ...result.items
            .filter((item) => item.status === 'failed')
            .map((item) => `${item.service_type}:${item.date}`),
        ],
      ));
      let refreshed = true;
      try {
        await onConfirmed();
        const refreshedConstraints = await fetchAssignmentConstraints(year, month);
        setConstraintsByDate(Object.fromEntries(
          refreshedConstraints.dates.map((item) => [item.date, item.blocked_workers]),
        ));
      } catch {
        refreshed = false;
        setError('Schedules were saved, but the calendar could not be refreshed. Reload the page to see the latest assignments.');
      }

      const needsAttention = result.summary.failed + locallyBlockedKeys.length;
      if (needsAttention === 0 && refreshed) {
        onClose();
        return;
      }

      setSaveSummary(
        `${result.summary.created} schedule${result.summary.created === 1 ? '' : 's'} saved. ${needsAttention} need${needsAttention === 1 ? 's' : ''} attention.`,
      );
    } catch (requestError) {
      setEditableRows((current) => current.map((row) =>
        selectedRowKeys.has(getRowKey(row))
          ? { ...row, conflicts: getScheduleRequestConflicts(requestError, row.date) }
          : row,
      ));
      setError('Generated schedules could not be saved. Review the highlighted rows and try again.');
    } finally {
      setConfirming(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-start justify-center overflow-y-auto bg-slate-950/50 px-4 py-4 sm:items-center sm:py-6">
      <section className="flex max-h-[calc(100dvh-2rem)] w-full min-w-0 max-w-[1500px] flex-col overflow-hidden rounded-lg bg-white shadow-xl sm:max-h-[calc(100dvh-3rem)]">
        <div className="flex shrink-0 items-start justify-between gap-4 border-b border-slate-200 p-4 sm:p-5">
          <div className="min-w-0">
            <p className="text-sm font-semibold uppercase tracking-wide text-amber-700">Auto generate</p>
            <h2 className="mt-1 text-xl font-bold text-slate-950">Schedules for {monthLabel}</h2>
            <p className="mt-1 text-sm text-slate-600">
              Select one or more services, optionally limit each role to chosen servers, then review before saving.
            </p>
          </div>
          <button type="button" onClick={onClose} className="inline-flex h-9 w-9 items-center justify-center rounded-md text-slate-500 hover:bg-slate-100 hover:text-slate-950" aria-label="Close auto-generation">
            <FaTimes />
          </button>
        </div>

        <div className="min-w-0 space-y-5 overflow-y-auto p-4 sm:p-5">
          {error && <div className="rounded-md border border-red-200 bg-red-50 px-3 py-2 text-sm font-medium text-red-700">{error}</div>}
          {saveSummary && <div className="rounded-md border border-amber-200 bg-amber-50 px-3 py-2 text-sm font-medium text-amber-800">{saveSummary}</div>}

          <form onSubmit={handlePreview} className="space-y-5 rounded-md border border-slate-200 bg-slate-50 p-4">
            <div className="grid gap-5 lg:grid-cols-[180px_minmax(0,1fr)]">
              <div>
                <p className="text-xs font-bold uppercase text-slate-500">Month</p>
                <p className="mt-1 text-sm font-bold text-slate-950">{monthLabel}</p>
              </div>
              <fieldset>
                <legend className="text-xs font-bold uppercase text-slate-500">Service types</legend>
                <div className="mt-2 flex flex-wrap gap-x-5 gap-y-2">
                  {availableServiceTypes.map((serviceType) => (
                    <label key={serviceType._id} className="flex items-center gap-2 text-sm font-semibold text-slate-700">
                      <input
                        type="checkbox"
                        checked={selectedServiceTypes.has(serviceType.code)}
                        onChange={() => {
                          const next = new Set(selectedServiceTypes);
                          next.has(serviceType.code) ? next.delete(serviceType.code) : next.add(serviceType.code);
                          setSelectedServiceTypes(next);
                          resetPreview();
                        }}
                        className="h-4 w-4 rounded border-slate-300 text-amber-600 focus:ring-amber-500"
                      />
                      {serviceType.name} ({weekdays[serviceType.recurrence.weekday ?? 0]})
                    </label>
                  ))}
                  {!availableServiceTypes.length && <p className="text-sm text-slate-600">No service types are enabled for auto-generation.</p>}
                </div>
              </fieldset>
            </div>

            <div className="flex flex-wrap gap-x-6 gap-y-2 border-t border-slate-200 pt-4">
              <label className="flex items-center gap-2 text-sm font-semibold text-slate-700">
                <input
                  type="checkbox"
                  checked={includeOptionalRoles}
                  onChange={(event) => {
                    setIncludeOptionalRoles(event.target.checked);
                    resetPreview();
                  }}
                  className="h-4 w-4 rounded border-slate-300 text-amber-600 focus:ring-amber-500"
                />
                Include optional roles
              </label>
              {selectedServiceTypes.has('main') && (
                <label className="flex items-center gap-2 text-sm font-semibold text-slate-700">
                  <input
                    type="checkbox"
                    checked={allowYouthBackupFallback}
                    onChange={(event) => {
                      setAllowYouthBackupFallback(event.target.checked);
                      resetPreview();
                    }}
                    className="h-4 w-4 rounded border-slate-300 text-amber-600 focus:ring-amber-500"
                  />
                  Youth backup fallback
                </label>
              )}
            </div>

            {selectedServiceTypeConfigs.length > 0 && (
              <div className="space-y-3 border-t border-slate-200 pt-4">
                <div>
                  <p className="text-xs font-bold uppercase text-slate-500">Preselect servers by role (optional)</p>
                  <p className="mt-1 text-sm text-slate-600">Leave a role empty to let auto-generation use every eligible server.</p>
                </div>
                {selectedServiceTypeConfigs.map((serviceType) => (
                  <details key={serviceType.code} className="rounded-md border border-slate-200 bg-white p-3">
                    <summary className="cursor-pointer text-sm font-bold text-slate-900">{serviceType.name} server pools</summary>
                    <div className="mt-3 grid gap-4 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4">
                      {[...serviceType.assignment_slots]
                        .sort((a, b) => a.display_order - b.display_order)
                        .filter((slot) => slot.required || includeOptionalRoles)
                        .map((slot) => {
                          const eligibility = getSlotEligibility(slot, serviceType.worker_eligibility);
                          const options = workers.filter((worker) =>
                            worker.status === 'active' &&
                            slot.allowed_roles.some((role) => worker.roles.includes(role)) &&
                            isWorkerEligible(worker, eligibility, workerGroups),
                          );
                          const selectedWorkers = workerPools[serviceType.code]?.[slot.key] ?? [];

                          return (
                            <div key={slot.key} className="block min-w-0">
                              <span className="text-sm font-semibold text-slate-700">{slot.label}{slot.required ? ' *' : ''}</span>
                              <div className="mt-1 max-h-36 space-y-1 overflow-y-auto rounded-md border border-slate-300 bg-white p-2">
                                {options.map((worker) => {
                                  const matchingRoles = slot.allowed_roles.filter((role) => worker.roles.includes(role));
                                  const checked = selectedWorkers.includes(worker._id);
                                  return (
                                    <label key={worker._id} className="flex items-start gap-2 rounded px-1 py-1 text-sm hover:bg-slate-50">
                                      <input
                                        type="checkbox"
                                        checked={checked}
                                        onChange={() => {
                                          const workerIds = checked
                                            ? selectedWorkers.filter((id) => id !== worker._id)
                                            : [...selectedWorkers, worker._id];
                                          setWorkerPools((current) => ({
                                            ...current,
                                            [serviceType.code]: {
                                              ...(current[serviceType.code] ?? {}),
                                              [slot.key]: workerIds,
                                            },
                                          }));
                                          resetPreview();
                                        }}
                                        className="mt-0.5 h-4 w-4 shrink-0 rounded border-slate-300 text-amber-600 focus:ring-amber-500"
                                      />
                                      <span>
                                        {worker.name}{slot.allowed_roles.length > 1 ? ` (${matchingRoles.join(' / ')})` : ''}
                                      </span>
                                    </label>
                                  );
                                })}
                                {!options.length && <p className="px-1 py-1 text-sm text-slate-500">No eligible servers</p>}
                              </div>
                              <span className="mt-1 block text-xs text-slate-500">{selectedWorkers.length ? `${selectedWorkers.length} selected` : 'All eligible servers'}</span>
                            </div>
                          );
                        })}
                    </div>
                  </details>
                ))}
              </div>
            )}

            <div className="flex justify-end">
              <button type="submit" disabled={loadingPreview || !selectedServiceTypeConfigs.length} className="inline-flex h-10 items-center justify-center rounded-md bg-slate-950 px-5 text-sm font-semibold text-white hover:bg-slate-800 disabled:cursor-not-allowed disabled:opacity-60">
                {loadingPreview ? 'Generating...' : 'Generate preview'}
              </button>
            </div>
          </form>

          {preview && selectedServiceTypeConfigs.map((serviceType) => {
            const rows = editableRows.filter((row) => row.service_type === serviceType.code);
            if (!rows.length) return null;
            const serviceSelectedDates = new Set(
              rows.filter((row) => selectedRowKeys.has(getRowKey(row))).map((row) => row.date),
            );

            return (
              <EditableScheduleTable
                key={serviceType.code}
                title={`${serviceType.name} preview`}
                selectedLabel="generated schedule"
                saveLabel="Save all selected services"
                serviceType={serviceType}
                rows={rows}
                workers={workers}
                workerGroups={workerGroups}
                selectedDates={serviceSelectedDates}
                saving={confirming}
                onRowsChange={(nextRows) => {
                  const replacements = new Map(nextRows.map((row) => [getRowKey(row), row]));
                  setEditableRows((current) => current.map((row) => replacements.get(getRowKey(row)) ?? row));
                }}
                constraintsByDate={getConstraintsForService(serviceType.code)}
                onSelectedDatesChange={(dates) => {
                  const next = new Set(
                    [...selectedRowKeys].filter((key) => !key.startsWith(`${serviceType.code}:`)),
                  );
                  dates.forEach((date) => next.add(`${serviceType.code}:${date}`));
                  setSelectedRowKeys(next);
                }}
                onSave={handleConfirm}
              />
            );
          })}
        </div>
      </section>
    </div>
  );
};

const getRowKey = (row: Pick<AutoGeneratedScheduleRow, 'service_type' | 'date'>) =>
  `${row.service_type}:${row.date}`;

const weekdays = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];

export default AutoGenerateScheduleModal;
