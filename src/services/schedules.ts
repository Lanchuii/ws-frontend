export const fetchSchedules = async (): Promise<WorshipSchedule[]> => {
  try {
    const response = await api.get('/schedules');
    return normalizeScheduleResponse(response.data);
  } catch (error) {
    const response = await api.get(`${getApiBaseUrl()}/schedule/`);
    return normalizeScheduleResponse(response.data);
  }
};

export const fetchMyAssignments = async (): Promise<MyAssignmentsResult> => {
  const response = await api.get('/schedules/my-assignments');
  const data = response.data.data;
  const worker = isRecord(data?.worker) ? data.worker : null;

  return {
    worker: worker
      ? {
          id: getString(worker, '_id') ?? '',
          name: getString(worker, 'name') ?? '',
          roles: normalizeWorkerRoles(getArray(worker, 'roles')),
        }
      : null,
    items: normalizeScheduleResponse(data?.items ?? []),
  };
};

