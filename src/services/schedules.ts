export const confirmAutoGeneration = async (
  payload: AutoGenerationConfirmPayload,
): Promise<AutoGenerationConfirmResult> => {
  const response = await api.post('/schedules/auto-generation/confirm', payload);
  const data = isRecord(response.data) && isRecord(response.data.data)
    ? response.data.data
    : response.data;
  const result = data as unknown as {
    items?: Array<Record<string, unknown>>;
    summary?: AutoGenerationConfirmResult['summary'];
  };

  return {
    items: (result.items ?? []).map((item) => {
      const schedule = isRecord(item.schedule) ? item.schedule : undefined;
      return {
        date: getString(item, 'date') ?? '',
        service_type:
          getString(item, 'service_type') ??
          (schedule ? getString(schedule, 'serviceType') : undefined) ??
          (schedule ? getString(schedule, 'service_type') : undefined) ??
          'main',
        status: getString(item, 'status') === 'created' ? 'created' as const : 'failed' as const,
        schedule: schedule ? normalizeSchedule(schedule) ?? undefined : undefined,
        message: getString(item, 'message'),
        conflicts: Array.isArray(item.conflicts)
          ? item.conflicts as ScheduleConflict[]
          : undefined,
      };
    }),
    summary: result.summary ?? { submitted: 0, created: 0, failed: 0 },
  };
};

